"""Generate src/affixes_data.rs from blizzhackers/d2data (D2R JSON game tables).

Usage: python3 -I research/gen_affixes.py <dir with magicprefix.json, magicsuffix.json, misc.json,
       monstats.json, allstrings-eng.json> > src/affixes_data.rs
Fetch the tables with:
  gh api repos/blizzhackers/d2data/contents/json/<name>.json -H "Accept: application/vnd.github.raw" > <name>.json

Magic affix ids as the game stores them in ItemData (+0x48 magic prefix, +0x4E magic suffix;
live 2026-11-18 on 14 owned items checked against their stat lists, e.g. a Battle Staff of
Teleportation with suffix 532): a suffix id is its magicsuffix.json key; a prefix id is
PREFIX_BASE + its magicprefix.json key, PREFIX_BASE being the highest magicsuffix key (785).
Names go through the English string table (the `Name` column is a string key; 45 prefixes and
131 suffixes are shown differently, e.g. "of Warmth" is "of Thawing"). Several ids share a name
(one row per item-type group), so builds are matched by the composed name, never by id.
Also: misc.txt base names and levels (the armor and weapon bases are in item_levels_data.rs and
weapons_data.rs) and the vendor NPCs' names by monstats row (`*hcIdx` = monster unit txt).
"""
import json
import sys

src = sys.argv[1]

# monstats `Id`s of the NPCs with a trade window (classic vendors, all five acts).
VENDORS = ["akara", "charsi", "gheed", "fara", "drognan", "elzix", "lysander", "ormus",
           "asheara", "hratli", "alkor", "jamella", "halbu", "larzuk", "malah", "drehya",
           "drehyaiced", "nihlathak"]


def load(name):
    return json.load(open(f"{src}/{name}"))


def rows(name):
    t = load(name)
    return t if isinstance(t, list) else list(t.values())


def rust_str(s):
    return json.dumps(s, ensure_ascii=False)


strings = load("allstrings-eng.json")


def shown(key):
    s = strings.get(key)
    return s if isinstance(s, str) and s else key


prefixes = load("magicprefix.json")
suffixes = load("magicsuffix.json")
prefix_base = max(int(k) for k in suffixes)
assert prefix_base == 785, f"PREFIX_BASE changed: {prefix_base} (re-verify live)"


def affixes(table, shift):
    out = []
    for k, v in table.items():
        if v.get("Name"):
            out.append((int(k) + shift, shown(v["Name"]), int(v.get("levelreq", 0) or 0)))
    return sorted(out)


print("//! Generated by `research/gen_affixes.py` from `blizzhackers/d2data` (D2R tables). Do not edit by hand.")
for const, table, shift, what in [
    ("PREFIXES", prefixes, prefix_base, f"magic prefix ({prefix_base} + magicprefix row; the base is the highest magicsuffix row)"),
    ("SUFFIXES", suffixes, 0, "magic suffix (magicsuffix row)"),
]:
    data = affixes(table, shift)
    print()
    print(f"/// ({what} id, English name, `levelreq`), sorted by id.")
    print(f"pub const {const}: &[(u16, &str, u32)] = &[")
    for i, name, lvl in data:
        print(f"    ({i}, {rust_str(name)}, {lvl}),")
    print("];")

misc = sorted((r["code"], int(r.get("levelreq", 0) or 0), shown(r.get("namestr") or r["name"]))
              for r in rows("misc.json") if r.get("code"))
assert len({c for c, _, _ in misc}) == len(misc), "duplicate code in misc.json"
print()
print("/// (item code, `levelreq`, English name) per misc.txt row, sorted by code.")
print("pub const MISC: &[(&str, u32, &str)] = &[")
for code, lvl, name in misc:
    print(f"    ({rust_str(code)}, {lvl}, {rust_str(name)}),")
print("];")

mon = {r.get("Id"): r for r in rows("monstats.json")}
vendors = sorted((int(mon[v]["*hcIdx"]), shown(mon[v]["NameStr"])) for v in VENDORS)
print()
print("/// (monstats `*hcIdx` = monster unit txt, English name) of the vendor NPCs, sorted by row.")
print("pub const VENDORS: &[(u32, &str)] = &[")
for i, name in vendors:
    print(f"    ({i}, {rust_str(name)}),")
print("];")

for fn, const, doc in [
    ("prefix", "PREFIXES", "magic prefix"),
    ("suffix", "SUFFIXES", "magic suffix"),
]:
    print()
    print(f"/// The {doc} with memory id `id`: (English name, `levelreq`); `None` if unknown.")
    print("#[must_use]")
    print(f"pub fn {fn}(id: u16) -> Option<(&'static str, u32)> {{")
    print(f"    {const}.binary_search_by_key(&id, |&(i, _, _)| i).ok()")
    print(f"        .and_then(|i| {const}.get(i))")
    print("        .map(|&(_, name, lvl)| (name, lvl))")
    print("}")
print()
print("/// The misc.txt row with item code `code`: (`levelreq`, English name); `None` if unknown.")
print("#[must_use]")
print("pub fn misc(code: &str) -> Option<(u32, &'static str)> {")
print("    MISC.binary_search_by_key(&code, |&(c, _, _)| c).ok()")
print("        .and_then(|i| MISC.get(i))")
print("        .map(|&(_, lvl, name)| (lvl, name))")
print("}")
print()
print("/// The English name of the vendor NPC with monstats row `txt`; `None` for other monsters.")
print("#[must_use]")
print("pub fn vendor(txt: u32) -> Option<&'static str> {")
print("    VENDORS.binary_search_by_key(&txt, |&(i, _)| i).ok()")
print("        .and_then(|i| VENDORS.get(i))")
print("        .map(|&(_, name)| name)")
print("}")
