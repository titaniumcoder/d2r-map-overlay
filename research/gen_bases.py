"""Generate src/bases_data.rs from blizzhackers/d2data (D2R JSON game tables).

Usage: python3 -I research/gen_bases.py <dir with weapons.json, armor.json, misc.json, itemtypes.json> > src/bases_data.rs
The output is rustfmt-clean (check with `cargo fmt --check`).
Fetch the tables with:
  for f in weapons armor misc itemtypes; do
    gh api repos/blizzhackers/d2data/contents/json/$f.json -H "Accept: application/vnd.github.raw" > $f.json
  done
One row per equippable base (weapons, armor, rings, amulets): the body slot it goes in, its
weapon kind (the item type, with the class-only variants folded into the generic one:
abow -> bow, ajav -> jave, aspe -> spea, h2h2 -> h2h; "" for armor), the class it is
restricted to (itemtypes.txt `Class` of its type: 0 amazon .. 7 warlock) and its strength and
dexterity requirements. The vendor panel's stat comparison (src/gear_score.rs) reads it; the
item's damage and defense come from its own stat list, not from here.
"""
import json
import sys

src = sys.argv[1]


def table(name):
    t = json.load(open(f"{src}/{name}.json"))
    return t if isinstance(t, list) else list(t.values())


CLASSES = {"ama": 0, "sor": 1, "nec": 2, "pal": 3, "bar": 4, "dru": 5, "ass": 6, "war": 7}
type_class = {r["Code"]: CLASSES[r["Class"]] for r in table("itemtypes") if r.get("Class") in CLASSES}
ARMOR_SLOTS = {
    "helm": 1, "circ": 1, "pelt": 1, "phlm": 1,
    "tors": 3,
    "shie": 5, "ashd": 5, "head": 5, "grim": 5,
    "belt": 8, "boot": 9, "glov": 10,
}
MISC_SLOTS = {"amul": 2, "ring": 6}
FOLD = {"abow": "bow", "ajav": "jave", "aspe": "spea", "h2h2": "h2h"}

rows = []
for r in table("weapons"):
    ty = r.get("type")
    if not r.get("code") or ty == "tpot":  # throwing potions: no slot worth comparing
        continue
    rows.append((r["code"], 4, FOLD.get(ty, ty), type_class.get(ty), int(r.get("reqstr") or 0), int(r.get("reqdex") or 0)))
for r in table("armor"):
    ty = r.get("type")
    if r.get("code") and ty in ARMOR_SLOTS:
        rows.append((r["code"], ARMOR_SLOTS[ty], "", type_class.get(ty), int(r.get("reqstr") or 0), int(r.get("reqdex") or 0)))
for r in table("misc"):
    ty = r.get("type")
    if r.get("code") and ty in MISC_SLOTS:
        rows.append((r["code"], MISC_SLOTS[ty], "", None, 0, 0))
rows.sort()
codes = [r[0] for r in rows]
assert len(codes) == len(set(codes)), "duplicate code"

print("//! Generated by `research/gen_bases.py` from blizzhackers/d2data (D2R). Do not edit by hand.")
print()
print("/// One equippable base item.")
print("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
print("pub struct Base {")
print("    /// The 3-character item code.")
print("    pub code: &'static str,")
print("    /// `item_data::BODY` slot it is worn in (1 helm, 2 amulet, 3 body, 4 weapon, 5 shield,")
print("    /// 6 ring, 8 belt, 9 boots, 10 gloves).")
print("    pub slot: u8,")
print('    /// Weapon kind (items.txt type: "bow", "jave", "swor", ...); "" for armor and jewellery.')
print("    pub kind: &'static str,")
print("    /// The class it is restricted to (player txt row 0 amazon .. 7 warlock); `None` = any.")
print("    pub class: Option<u8>,")
print("    /// Strength and dexterity requirements.")
print("    pub str: u32,")
print("    pub dex: u32,")
print("}")
print()
print("/// One [`BASES`] row: (code, slot, kind, class, str, dex), the fields of [`Base`].")
print("pub type Row = (&'static str, u8, &'static str, Option<u8>, u32, u32);")
print()
print("/// Every equippable base, sorted by code.")
print("pub const BASES: &[Row] = &[")
for code, slot, kind, cls, s, d in rows:
    cls = "None" if cls is None else f"Some({cls})"
    print(f'    ("{code}", {slot}, "{kind}", {cls}, {s}, {d}),')
print("];")
print()
print("/// The base with item code `code`.")
print("#[must_use]")
print("pub fn base(code: &str) -> Option<Base> {")
print("    let i = BASES.binary_search_by(|row| row.0.cmp(code)).ok()?;")
print("    let &(code, slot, kind, class, str, dex) = BASES.get(i)?;")
print("    Some(Base {")
print("        code,")
print("        slot,")
print("        kind,")
print("        class,")
print("        str,")
print("        dex,")
print("    })")
print("}")
