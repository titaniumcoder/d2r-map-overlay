"""Generate crates/core/src/inv_sizes_data.rs from blizzhackers/d2data (D2R JSON game tables).

Usage: python3 -I research/gen_inv_sizes.py <dir with weapons.json, armor.json, misc.json> > crates/core/src/inv_sizes_data.rs
Fetch the tables as research/gen_bases.py says. One row per item code: its size in inventory
cells (`invwidth`, `invheight`), for the in-game UI marks' frames around stored items.
"""
import json
import sys

src = sys.argv[1]


def table(name):
    t = json.load(open(f"{src}/{name}.json"))
    return t if isinstance(t, list) else list(t.values())


sizes = {}
for name in ("armor", "weapons", "misc"):
    for r in table(name):
        code = r.get("code")
        if not code:
            continue
        size = (int(r["invwidth"]), int(r["invheight"]))
        assert sizes.get(code, size) == size, code
        assert 1 <= size[0] <= 4 and 1 <= size[1] <= 4, (code, size)
        sizes[code] = size

rows = sorted(sizes.items())
print("//! Generated by `research/gen_inv_sizes.py` from blizzhackers/d2data (D2R). Do not edit by hand.")
print()
print("/// (item code, width, height) in inventory cells per armor / weapons / misc row, sorted by code.")
print(f"pub static INV_SIZES: [(&str, u8, u8); {len(rows)}] = [")
for code, (w, h) in rows:
    print(f'    ("{code}", {w}, {h}),')
print("];")
print()
print("/// The item's size in inventory cells (width, height); `None` for an unknown code.")
print("#[must_use]")
print("pub fn size(code: &str) -> Option<(u8, u8)> {")
print("    INV_SIZES")
print("        .binary_search_by(|row| row.0.cmp(code))")
print("        .ok()")
print("        .and_then(|i| INV_SIZES.get(i))")
print("        .map(|&(_, w, h)| (w, h))")
print("}")
print()
print("#[cfg(test)]")
print("mod tests {")
print("    use super::*;")
print()
print("    #[test]")
print("    fn sizes_by_code() {")
print('        assert_eq!(size("cm3"), Some((1, 3)), "grand charm");')
print('        assert_eq!(size("box"), Some((2, 2)), "Horadric Cube");')
print('        assert_eq!(size("7cr"), Some((2, 3)), "Phase Blade");')
print('        assert_eq!(size("rin"), Some((1, 1)));')
print('        assert_eq!(size("aar"), Some((2, 3)), "Ancient Armor");')
print('        assert_eq!(size("zzz"), None);')
print("        assert!(INV_SIZES.is_sorted_by(|a, b| a.0 < b.0));")
print("    }")
print("}")
