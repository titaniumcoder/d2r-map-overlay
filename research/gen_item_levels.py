"""Generate src/item_levels_data.rs from blizzhackers/d2data (D2R JSON game tables).

Usage: python3 -I research/gen_item_levels.py <dir with uniqueitems.json, setitems.json, armor.json> > src/item_levels_data.rs
Fetch the tables with:
  gh api repos/blizzhackers/d2data/contents/json/uniqueitems.json -H "Accept: application/vnd.github.raw" > uniqueitems.json
  gh api repos/blizzhackers/d2data/contents/json/setitems.json -H "Accept: application/vnd.github.raw" > setitems.json
  gh api repos/blizzhackers/d2data/contents/json/armor.json -H "Accept: application/vnd.github.raw" > armor.json
The required character level of an equipped unique/set item is looked up by its
ItemData FILE_INDEX (the table row's `*ID`; verified live 2026-11-15: Khalim's Flail
unique 127, Cleglaw's Claw set 7) in the `lvl req` column. Base items (normal, magic,
rare, ...) are looked up by their 4-char item code: armor rows here, weapons rows in
src/weapons_data.rs (its `levelreq` column, research/gen_weapons.py). Base-item levels
of magic/rare items are the BASE requirement: affixes can raise the real one.
Rows without a `lvl req` (10 uniqueitems) are left out; the lookup answers None.
"""
import json
import sys

src = sys.argv[1]


def rust_str(s):
    return json.dumps(s, ensure_ascii=False)


def table(name):
    t = json.load(open(f"{src}/{name}"))
    return t if isinstance(t, list) else list(t.values())


print("//! Generated by `research/gen_item_levels.py` from `blizzhackers/d2data` (D2R tables). Do not edit by hand.")

for const, file, what in [
    ("UNIQUE_LEVELS", "uniqueitems.json", "uniqueitems"),
    ("SET_LEVELS", "setitems.json", "setitems"),
]:
    rows = sorted((r["*ID"], r["lvl req"]) for r in table(file) if "*ID" in r and isinstance(r.get("lvl req"), int))
    ids = [i for i, _ in rows]
    assert len(ids) == len(set(ids)), f"duplicate *ID in {file}"
    print()
    print(f"/// ({what} row `*ID`, `lvl req`), sorted by row. Rows without a `lvl req` are left")
    print("/// out: the lookup answers `None`.")
    print(f"pub const {const}: &[(u32, u32)] = &[")
    for i, lvl in rows:
        print(f"    ({i}, {lvl}),")
    print("];")

armor = sorted(
    ((r["code"], int(r["levelreq"]), r["name"]) for r in table("armor.json") if r.get("code")),
    key=lambda t: t[0],
)
codes = [c for c, _, _ in armor]
assert len(codes) == len(set(codes)), "duplicate code in armor.json"
print()
print("/// (item code, `levelreq`, `name`) per armor.txt row, sorted by code. The name is the")
print("/// base item's display name (a magic/rare item's real name comes from its affixes).")
print(f"pub const ARMOR: &[(&str, u32, &str); {len(armor)}] = &[")
for code, lvl, name in armor:
    print(f"    ({rust_str(code)}, {lvl}, {rust_str(name)}),")
print("];")

print()
print("/// The `lvl req` of uniqueitems row `row` (`ItemData` `FILE_INDEX`), `None` if unknown.")
print("/// Only meaningful for an identified item: the index is filled once identified")
print("/// (see `item_data::FILE_INDEX`).")
print("#[must_use]")
print("pub fn unique_level(row: u32) -> Option<u32> {")
print("    UNIQUE_LEVELS.binary_search_by_key(&row, |&(i, _)| i).ok()")
print("        .and_then(|i| UNIQUE_LEVELS.get(i))")
print("        .map(|&(_, lvl)| lvl)")
print("}")
print()
print("/// The `lvl req` of setitems row `row` (`ItemData` `FILE_INDEX`), `None` if unknown.")
print("/// Only meaningful for an identified item: the index is filled once identified")
print("/// (see `item_data::FILE_INDEX`).")
print("#[must_use]")
print("pub fn set_level(row: u32) -> Option<u32> {")
print("    SET_LEVELS.binary_search_by_key(&row, |&(i, _)| i).ok()")
print("        .and_then(|i| SET_LEVELS.get(i))")
print("        .map(|&(_, lvl)| lvl)")
print("}")
print()
print("/// The `levelreq` of the armor.txt row with item code `code`, `None` if unknown.")
print("#[must_use]")
print("pub fn armor_level(code: &str) -> Option<u32> {")
print("    ARMOR.binary_search_by_key(&code, |&(c, _, _)| c).ok()")
print("        .and_then(|i| ARMOR.get(i))")
print("        .map(|&(_, lvl, _)| lvl)")
print("}")
print()
print("/// The armor.txt display name of item code `code`, `None` if unknown.")
print("#[must_use]")
print("pub fn armor_name(code: &str) -> Option<&'static str> {")
print("    ARMOR.binary_search_by_key(&code, |&(c, _, _)| c).ok()")
print("        .and_then(|i| ARMOR.get(i))")
print("        .map(|&(_, _, name)| name)")
print("}")
