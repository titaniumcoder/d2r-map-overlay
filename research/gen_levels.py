"""Generate src/levels_data.rs from blizzhackers/d2data (D2R JSON game tables).

Usage: python3 -I research/gen_levels.py <dir with levels.json, monstats.json, superuniques.json, allstrings-eng.json> > src/levels_data.rs
Fetch the tables with:
  gh api repos/blizzhackers/d2data/contents/json/levels.json -H "Accept: application/vnd.github.raw" > levels.json
  gh api repos/blizzhackers/d2data/contents/json/monstats.json -H "Accept: application/vnd.github.raw" > monstats.json
  gh api repos/blizzhackers/d2data/contents/json/superuniques.json -H "Accept: application/vnd.github.raw" > superuniques.json
  gh api repos/blizzhackers/d2data/contents/json/allstrings-eng.json -H "Accept: application/vnd.github.raw" > allstrings-eng.json
Area names are the displayed English strings: levels.txt LevelName is a string-table key, and
several keys are old internal names ("Cellar of Pity" shows as "Frozen River", "Hell1" as
"Abaddon"), so the name is looked up in allstrings-eng.json, falling back to the key.
Monster levels are the expansion columns (MonLvlEx, MonLvlEx(N), MonLvlEx(H)).
Immunities (IMMUNITIES) are resist >= 100 in the monstats Res* columns of the spawned types.
"""
import json
import sys

src = sys.argv[1]
levels = json.load(open(f"{src}/levels.json"))
monstats = json.load(open(f"{src}/monstats.json"))
levels = levels if isinstance(levels, list) else list(levels.values())
monstats = monstats if isinstance(monstats, list) else list(monstats.values())
mon = {r.get("Id"): r for r in monstats}
supers = json.load(open(f"{src}/superuniques.json"))
strings = json.load(open(f"{src}/allstrings-eng.json"))
KEEP_KEY = {"Duriel's Lair", "Moo Moo Farm"}
supers = supers if isinstance(supers, list) else list(supers.values())

# Monster preset txt id of a superunique's spawn point = this + hcIdx.
SUPERUNIQUE_PRESET_BASE = 751

# Quest bosses with a fixed level (monstats Level columns), and the level id they live in.
BOSSES = [
    ("Blood Raven", "bloodraven", 17),
    ("Griswold", "griswold", 38),
    ("Andariel", "andariel", 37),
    ("Radament", "radament", 49),
    ("Summoner", "summoner", 74),
    ("Duriel", "duriel", 73),
    ("Mephisto", "mephisto", 102),
    ("Izual", "izual", 105),
    ("Diablo", "diablo", 108),
    ("Nihlathak", "nihlathakboss", 124),
    ("Baal", "baalcrab", 132),
]

# Baal's other monstats forms, also drawn as a boss (not his minions, tentacles or the council).
# "baaltaunt" is left out: it is the voice in the Worldstone Keep, not a form that fights.
BAAL_FORMS = ["baalthrone", "baalcrabstairs", "baalclone"]


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


print("//! Generated by research/gen_levels.py from blizzhackers/d2data (D2R tables). Do not edit by hand.")
print()
print("/// (level id, area name, expansion monster level for Normal, Nightmare, Hell).")
print("pub const LEVELS: &[(u32, &str, [u8; 3])] = &[")
for r in sorted(levels, key=lambda r: r.get("Id", 0)):
    lid, key = r.get("Id"), r.get("LevelName") or r.get("Name") or ""
    # Two keys collide in the merged string table with an unrelated entry; the game shows
    # the key itself for these (Duriel's Lair, the cow level).
    name = key if key in KEEP_KEY else (strings.get(key) or key)
    lv = [r.get("MonLvlEx") or 0, r.get("MonLvlEx(N)") or 0, r.get("MonLvlEx(H)") or 0]
    if lid is None or lid == 0:
        continue
    print(f"    ({lid}, {rs_str(name)}, [{lv[0]}, {lv[1]}, {lv[2]}]),")
print("];")
print()
print("/// (boss name, level id, fixed monster level for Normal, Nightmare, Hell).")
print("pub const BOSSES: &[(&str, u32, [u8; 3])] = &[")
for name, key, lid in BOSSES:
    r = mon[key]
    print(f"    ({rs_str(name)}, {lid}, [{r['Level']}, {r['Level(N)']}, {r['Level(H)']}]),")
print("];")
print()
print("/// (monster preset txt id = 751 + hcIdx, superunique name), sorted by id.")
print("pub const SUPERUNIQUES: &[(u32, &str)] = &[")
for r in sorted(supers, key=lambda r: r["hcIdx"]):
    print(f"    ({SUPERUNIQUE_PRESET_BASE + r['hcIdx']}, {rs_str(r['Superunique'])}),")
print("];")
print()
print("/// Monster txt ids (hcIdx) with a monstats `Align` (1 ally, 2 neutral): hirelings, summons,")
print("/// town NPCs and critters. Never enemies.")
print("pub const NON_HOSTILE_MONSTERS: &[u32] = &[")
for i in sorted(int(r["*hcIdx"]) for r in monstats if r.get("Align") not in (None, "", 0)):
    print(f"    {i},")
print("];")
print()
print("/// Monster txt ids (hcIdx) of the quest bosses in BOSSES plus Baal's other forms (throne,")
print("/// stairs, clone), sorted: drawn as a boss icon while alive.")
print("pub const BOSS_MONSTERS: &[u32] = &[")
for i in sorted({int(mon[key]["*hcIdx"]) for key in [k for _, k, _ in BOSSES] + BAAL_FORMS}):
    print(f"    {i},")
print("];")
print()

# Immunities: a resistance of 100 or more. Physical is monstats `ResDm` (damage resist).
IMMUNE = 100
RES_COLUMNS = ["ResDm", "ResFi", "ResCo", "ResLi", "ResPo", "ResMa"]  # physical, fire, cold, lightning, poison, magic
SUFFIXES = ["", "(N)", "(H)"]


def spawn_types(level, difficulty):
    """Distinct monstats ids spawned in `level` in `difficulty` (0 Normal, 1 Nightmare, 2 Hell).

    Normal: mon1..10 plus umon1..10 (the unique/champion candidates). Nightmare and Hell share
    nmon1..10 (the game picks uniques from the same list there). Empty and unknown keys are
    skipped; a key listed twice (a spawn weight) counts once."""
    prefixes = ["mon", "umon"] if difficulty == 0 else ["nmon"]
    keys = []
    for p in prefixes:
        for i in range(1, 11):
            k = level.get(f"{p}{i}")
            if k and k in mon and k not in keys:
                keys.append(k)
    return keys


print("/// One level in one difficulty: (distinct monster types that spawn, how many are immune to")
print("/// each damage type, the immunity bitmask of each type with any immunity); see IMMUNITIES.")
print("pub type AreaImmunities = (u8, [u8; 6], &'static [u8]);")
print()
print("/// (level id, per difficulty Normal, Nightmare, Hell: (distinct monster types that spawn,")
print("/// how many of them are immune (resist >= 100) to [physical, fire, cold, lightning, poison,")
print("/// magic], and the immunity bitmask of each type with any immunity (bit i = damage i of that")
print("/// order))). From levels `mon`/`umon` (Normal) and `nmon` (Nightmare, Hell) and the monstats")
print("/// `ResDm`/`ResFi`/`ResCo`/`ResLi`/`ResPo`/`ResMa` columns of that difficulty.")
print("#[rustfmt::skip] // one row per level as generated; rustfmt would spread each over many lines")
print("pub const IMMUNITIES: &[(u32, [AreaImmunities; 3])] = &[")
for r in sorted(levels, key=lambda r: r.get("Id", 0)):
    lid = r.get("Id")
    if lid is None or lid == 0:
        continue
    per_difficulty = []
    for d, suffix in enumerate(SUFFIXES):
        types = spawn_types(r, d)
        masks = [
            sum(1 << i for i, c in enumerate(RES_COLUMNS) if (mon[k].get(c + suffix) or 0) >= IMMUNE)
            for k in types
        ]
        immune = [sum(1 for m in masks if m & (1 << i)) for i in range(len(RES_COLUMNS))]
        immune_masks = [m for m in masks if m]
        per_difficulty.append(
            f"({len(types)}, [{', '.join(map(str, immune))}], &[{', '.join(map(str, immune_masks))}])"
        )
    print(f"    ({lid}, [{', '.join(per_difficulty)}]),")
print("];")
