"""Generate src/levels_data.rs from blizzhackers/d2data (D2R JSON game tables).

Usage: python3 -I research/gen_levels.py <dir with levels.json and monstats.json> > src/levels_data.rs
Fetch the tables with:
  gh api repos/blizzhackers/d2data/contents/json/levels.json -H "Accept: application/vnd.github.raw" > levels.json
  gh api repos/blizzhackers/d2data/contents/json/monstats.json -H "Accept: application/vnd.github.raw" > monstats.json
Monster levels are the expansion columns (MonLvlEx, MonLvlEx(N), MonLvlEx(H)).
"""
import json
import sys

src = sys.argv[1]
levels = json.load(open(f"{src}/levels.json"))
monstats = json.load(open(f"{src}/monstats.json"))
levels = levels if isinstance(levels, list) else list(levels.values())
monstats = monstats if isinstance(monstats, list) else list(monstats.values())
mon = {r.get("Id"): r for r in monstats}

# Quest bosses with a fixed level (monstats Level columns), and the level id they live in.
BOSSES = [
    ("Blood Raven", "bloodraven", 17),
    ("Griswold", "griswold", 38),
    ("Andariel", "andariel", 37),
    ("Radament", "radament", 49),
    ("Summoner", "summoner", 74),
    ("Duriel", "duriel", 73),
    ("Mephisto", "mephisto", 102),
    ("Izual", "izual", 105),
    ("Diablo", "diablo", 108),
    ("Nihlathak", "nihlathakboss", 124),
    ("Baal", "baalcrab", 132),
]


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


print("//! Generated by research/gen_levels.py from blizzhackers/d2data (D2R tables). Do not edit by hand.")
print()
print("/// (level id, area name, expansion monster level for Normal, Nightmare, Hell).")
print("pub const LEVELS: &[(u32, &str, [u8; 3])] = &[")
for r in sorted(levels, key=lambda r: r.get("Id", 0)):
    lid, name = r.get("Id"), r.get("LevelName") or r.get("Name") or ""
    lv = [r.get("MonLvlEx") or 0, r.get("MonLvlEx(N)") or 0, r.get("MonLvlEx(H)") or 0]
    if lid is None or lid == 0:
        continue
    print(f"    ({lid}, {rs_str(name)}, [{lv[0]}, {lv[1]}, {lv[2]}]),")
print("];")
print()
print("/// (boss name, level id, fixed monster level for Normal, Nightmare, Hell).")
print("pub const BOSSES: &[(&str, u32, [u8; 3])] = &[")
for name, key, lid in BOSSES:
    r = mon[key]
    print(f"    ({rs_str(name)}, {lid}, [{r['Level']}, {r['Level(N)']}, {r['Level(H)']}]),")
print("];")
