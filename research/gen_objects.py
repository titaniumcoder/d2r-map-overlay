"""Generate src/objects_data.rs from blizzhackers/d2data (D2R JSON game tables).

Usage: python3 -I research/gen_objects.py <dir with objects.json> > src/objects_data.rs && cargo fmt
(rustfmt lays out the number lists.)
Fetch the table with:
  gh api repos/blizzhackers/d2data/contents/json/objects.json -H "Accept: application/vnd.github.raw" > objects.json

The object unit's txt id (unit +0x04) is the objects.txt `*ID`.

Classification rule: by `OperateFn`, the function run when the object is clicked, not by the
`Name` or description text (both are unreliable: 236 "health wellforhell" is a shrine, it gave a
shrine type live, and several shrine rows are named "Dummy" or "manashrine"):
- OperateFn 2 (shrine) -> SHRINE_OBJECTS. All 92 such rows have SubClass 1 (shrine) too. The
  shrine's effect is the live ObjectData +0x08 shrine type, not this table.
- OperateFn 22 (well: refill health, mana, stamina) -> WELL_OBJECTS. Their SubClass is 0 or 32
  (well); the fountains named "well"/"Well" with SubClass 0 are wells in game too.
No row has both. Pools and fountains without an OperateFn (12 RogueFountain, 31 Fountain,
82 bubbling pool of blood) can't be used and are left out.
"""
import json
import sys

src = sys.argv[1]
table = json.load(open(f"{src}/objects.json"))
table = table if isinstance(table, list) else list(table.values())

SHRINE_FN = 2
WELL_FN = 22


def ids(fn):
    out = sorted(r["*ID"] for r in table if "*ID" in r and r.get("OperateFn") == fn)
    assert len(out) == len(set(out)), "duplicate *ID"
    return out


def emit(name, doc, values):
    print()
    print(doc)
    print(f"pub const {name}: &[u32] = &[")
    for i in range(0, len(values), 12):
        print("    " + " ".join(f"{v}," for v in values[i : i + 12]))
    print("];")


shrines, wells = ids(SHRINE_FN), ids(WELL_FN)
assert not set(shrines) & set(wells)
print("//! Generated by `research/gen_objects.py` from `blizzhackers/d2data` (D2R tables). Do not edit by hand.")
emit("SHRINE_OBJECTS", "/// `objects.txt` `*ID`s of shrines (`OperateFn` 2), sorted.", shrines)
emit("WELL_OBJECTS", "/// `objects.txt` `*ID`s of wells (`OperateFn` 22), sorted.", wells)
