"""Generate src/skills_data.rs from blizzhackers/d2data (D2R tables).

Usage: python3 -I research/gen_skills.py <dir with skills.json, skilldesc.json, allstrings-eng.json> > src/skills_data.rs
Fetch the tables with:
  gh api repos/blizzhackers/d2data/contents/json/skills.json -H "Accept: application/vnd.github.raw" > skills.json
  gh api repos/blizzhackers/d2data/contents/json/skilldesc.json -H "Accept: application/vnd.github.raw" > skilldesc.json
  gh api repos/blizzhackers/d2data/contents/json/allstrings-eng.json -H "Accept: application/vnd.github.raw" > allstrings-eng.json
Per class skill: skills.txt `*Id`, the displayed English name (skilldesc `str name` looked up in
the strings; "Levitate" shows as "Levitation Mastery"), the class (player txt row, the
`CLASSES` order below), the skill tree page / row / column (skilldesc SkillPage, SkillRow,
SkillColumn) and `reqlevel`.
Tree names: the `StrSklTabItemN` strings ("%+d to Fire Skills") minus the "+N to " prefix
and the " Skills" suffix ("Fire", "Warcries"). The
page → string mapping is not a formula (Necromancer page 1 is Curses), so it is spelled out in
`TREE_STRINGS` and checked against one known skill per page; the Warlock's page 2 is Eldritch
(Levitate, Mirrored Blades) and page 3 Chaos (Miasma Bolt, Abyss), per the class guides.
BASIC: the classless skills a player can put on a mouse button (Attack, Throw, scrolls...).
"""
import json
import re
import sys

src = sys.argv[1]
skills = json.load(open(f"{src}/skills.json"))
skills = [r for r in (skills if isinstance(skills, list) else skills.values()) if "*Id" in r]
descs = json.load(open(f"{src}/skilldesc.json"))
descs = descs if isinstance(descs, list) else list(descs.values())
desc = {r.get("skilldesc"): r for r in descs if r.get("skilldesc")}
strings = json.load(open(f"{src}/allstrings-eng.json"))

CLASSES = ["ama", "sor", "nec", "pal", "bar", "dru", "ass", "war"]
# Per class: the StrSklTabItemN number of skill pages 1, 2, 3.
TREE_STRINGS = {
    "ama": [3, 2, 1],
    "sor": [15, 14, 13],
    "nec": [8, 7, 9],
    "pal": [6, 5, 4],
    "bar": [11, 12, 10],
    "dru": [16, 17, 18],
    "ass": [19, 20, 21],
    "war": [24, 22, 23],
}
# (class, page, a skill on that page): guards TREE_STRINGS against a table change.
CHECKS = [
    ("ama", 1, "Magic Arrow"), ("ama", 2, "Inner Sight"), ("ama", 3, "Jab"),
    ("sor", 1, "Fire Bolt"), ("sor", 2, "Charged Bolt"), ("sor", 3, "Ice Bolt"),
    ("nec", 1, "Amplify Damage"), ("nec", 2, "Teeth"), ("nec", 3, "Raise Skeleton"),
    ("pal", 1, "Sacrifice"), ("pal", 2, "Might"), ("pal", 3, "Prayer"),
    ("bar", 1, "Bash"), ("bar", 2, "Blade Mastery"), ("bar", 3, "Howl"),
    ("dru", 1, "Raven"), ("dru", 2, "Wearwolf"), ("dru", 3, "Firestorm"),
    ("ass", 1, "Fire Trauma"), ("ass", 2, "Claw Mastery"), ("ass", 3, "Tiger Strike"),
    ("war", 1, "Summon Goatman"), ("war", 2, "Levitate"), ("war", 3, "Miasma Bolt"),
]
BASIC_IDS = [0, 1, 2, 3, 4, 5, 217, 218, 219, 220]


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def name_of(r):
    d = desc.get(r.get("skilldesc"))
    key = d.get("str name") if d else None
    return (strings.get(key) if key else None) or r["skill"]


by_name = {r["skill"]: r for r in skills if r.get("skill")}
for cls, page, skill in CHECKS:
    r = by_name[skill]
    got = (r.get("charclass"), desc[r["skilldesc"]]["SkillPage"])
    if got != (cls, page):
        sys.exit(f"tree check failed: {skill} is {got}, expected {(cls, page)}")


def tree_name(n):
    return re.sub(r"\s+Skills$", "", re.sub(r"^[%+d]+\s*to\s+", "", strings[f"StrSklTabItem{n}"]))


print("//! Generated by `research/gen_skills.py` from blizzhackers/d2data (D2R tables). Do not edit by hand.")
print()
print("/// One class skill and its place in the class's skill tree.")
print("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
print("pub struct SkillInfo {")
print("    /// skills.txt row (`*Id`), the id a `Skill` record carries.")
print("    pub id: u16,")
print("    /// Displayed English name.")
print("    pub name: &'static str,")
print("    /// Class (player txt row: 0 amazon … 7 warlock).")
print("    pub class: u8,")
print("    /// Skill tree page 1..=3 (index + 1 into [`TREES`]).")
print("    pub page: u8,")
print("    /// Grid row (1 = top) and column (1..=3) on the page.")
print("    pub row: u8,")
print("    pub col: u8,")
print("    /// Required character level.")
print("    pub req_level: u8,")
print("}")
print()
print("/// Every class skill, sorted by id.")
print("pub const SKILLS: &[SkillInfo] = &[")
for r in sorted(skills, key=lambda r: r["*Id"]):
    cls = r.get("charclass")
    if cls not in CLASSES:
        continue
    d = desc[r["skilldesc"]]
    print(
        f"    SkillInfo {{ id: {r['*Id']}, name: {rs_str(name_of(r))}, class: {CLASSES.index(cls)}, "
        f"page: {d['SkillPage']}, row: {d['SkillRow']}, col: {d['SkillColumn']}, req_level: {r.get('reqlevel') or 1} }},"
    )
print("];")
print()
print("/// Skill tree names per class (player txt row), pages 1, 2, 3.")
print("pub const TREES: [[&str; 3]; 8] = [")
for cls in CLASSES:
    print("    [" + ", ".join(rs_str(tree_name(n)) for n in TREE_STRINGS[cls]) + "],")
print("];")
print()
print("/// Classless skills a player can put on a mouse button: (id, displayed name).")
print("pub const BASIC: &[(u16, &str)] = &[")
for sid in BASIC_IDS:
    r = next((r for r in skills if r["*Id"] == sid), None)
    if r is None:
        sys.exit(f"gen_skills: skill id {sid} not in skills.json (d2data changed?)")
    print(f"    ({sid}, {rs_str(name_of(r))}),")
print("];")
print()
print("/// The class skill with skills.txt id `id`.")
print("pub fn skill(id: u16) -> Option<&'static SkillInfo> {")
print("    SKILLS.binary_search_by_key(&id, |s| s.id).ok().and_then(|i| SKILLS.get(i))")
print("}")
print()
print("/// The displayed name of skill `id`: a class skill or a [`BASIC`] one.")
print("pub fn name(id: u16) -> Option<&'static str> {")
print("    skill(id).map(|s| s.name).or_else(|| BASIC.iter().find(|(i, _)| *i == id).map(|(_, n)| *n))")
print("}")
