"""Generate crates/core/src/states_data.rs from blizzhackers/d2data (D2R tables).

Usage: python3 -I research/gen_states.py <dir with states.json> > crates/core/src/states_data.rs && cargo fmt
Fetch the table with:
  gh api repos/blizzhackers/d2data/contents/json/states.json -H "Accept: application/vnd.github.raw" > states.json

The state ids are the states.txt `*ID`s: bit n of the unit's state bitfield
(`offsets::stat_list::STATE_FLAGS`). The table keeps classic row order and appends the D2R
additions (189 desecrated = Terror Zone, the Warlock's states from 192 on). Only the internal
`state` name is emitted; the curated display names are in `buffs.rs`.
"""
import json
import sys

src = sys.argv[1]
table = json.load(open(f"{src}/states.json"))
rows = sorted(
    (r for r in (table if isinstance(table, list) else table.values()) if "*ID" in r),
    key=lambda r: r["*ID"],
)
ids = [r["*ID"] for r in rows]
assert ids == list(range(len(ids))), "states.txt ids are not 0..n contiguous"
# Fixed points checked live or relied on elsewhere.
assert rows[189]["state"] == "desecrated"
assert rows[120]["state"] == "feralrage"
assert rows[32]["state"] == "battleorders"

print("//! Generated by `research/gen_states.py` from `blizzhackers/d2data` (D2R tables). Do not edit by hand.")
print()
print("/// states.txt `state` names, indexed by `*ID` (the state bit number).")
print("pub const STATES: &[&str] = &[")
for r in rows:
    print(f'    "{r["state"]}",')
print("];")
