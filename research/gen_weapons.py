"""Generate src/weapons_data.rs from blizzhackers/d2data weapons.json (D2R tables).

Usage: python3 -I research/gen_weapons.py <dir with weapons.json> > src/weapons_data.rs
Fetch the table with:
  gh api repos/blizzhackers/d2data/contents/json/weapons.json -H "Accept: application/vnd.github.raw" > weapons.json
The "speed" column is the WSM (weapon speed modifier): negative faster, positive slower;
empty cells mean 0. wtype is the weapon class code (axe, bow, swor, pole, …) — carried but
unused by the current reader. "levelreq" is the required character level and "2handed" (1) marks a
two-handed weapon (staves, bows, xbows, polearms, two-hand swords/axes/hammers); both
feed the dashboard's gear grid.
"""
import json
import sys

src = sys.argv[1]
weapons = json.load(open(f"{src}/weapons.json"))
weapons = weapons if isinstance(weapons, list) else list(weapons.values())
rows = sorted(
    (
        (
            r["code"],
            int(r.get("speed") or 0),
            r.get("wtype") or "",
            int(r.get("levelreq") or 0),
            r.get("2handed") == 1,
            r.get("name") or "",
        )
        for r in weapons
        if r.get("code")
    ),
    key=lambda t: t[0],
)
codes = [c for c, *_ in rows]
assert len(codes) == len(set(codes)), "duplicate code in weapons.json"
print("//! Generated by `research/gen_weapons.py` from blizzhackers/d2data weapons.json (D2R). Do not edit by hand.")
print()
print("/// (item code, WSM weapon speed modifier, weapon class, required character level,")
print("/// two-handed, display name) per weapons.txt row; the speed is the classic `speed`")
print("/// column (negative = fast, positive = slow, 0 for empty cells).")
print(f"pub static WEAPONS: [(&str, i32, &str, u32, bool, &str); {len(rows)}] = [")
for code, speed, wtype, lvl, two_handed, name in rows:
    name = name.replace('"', '\\"')
    print(f'    ("{code}", {speed}, "{wtype}", {lvl}, {str(two_handed).lower()}, "{name}"),')
print("];")
print()
print("/// The WSM (weapon speed modifier) of `code`, or `None` if it is no weapon row.")
print("#[must_use]")
print("pub fn wsm(code: &str) -> Option<i32> {")
print("    WEAPONS")
print("        .binary_search_by(|(c, _, _, _, _, _)| c.cmp(&code))")
print("        .ok()")
print("        .and_then(|i| WEAPONS.get(i))")
print("        .map(|&(_, wsm, _, _, _, _)| wsm)")
print("}")
print()
print("/// The required character level of `code`'s weapon row, `None` if unknown.")
print("#[must_use]")
print("pub fn level(code: &str) -> Option<u32> {")
print("    WEAPONS")
print("        .binary_search_by(|(c, _, _, _, _, _)| c.cmp(&code))")
print("        .ok()")
print("        .and_then(|i| WEAPONS.get(i))")
print("        .map(|&(_, _, _, lvl, _, _)| lvl)")
print("}")
print()
print("/// Whether `code`'s weapon row is two-handed, `None` if the code is no weapon row.")
print("#[must_use]")
print("pub fn two_handed(code: &str) -> Option<bool> {")
print("    WEAPONS")
print("        .binary_search_by(|(c, _, _, _, _, _)| c.cmp(&code))")
print("        .ok()")
print("        .and_then(|i| WEAPONS.get(i))")
print("        .map(|&(_, _, _, _, two_handed, _)| two_handed)")
print("}")
print()
print("/// The display name of `code`'s weapon row, `None` if unknown.")
print("#[must_use]")
print("pub fn name(code: &str) -> Option<&'static str> {")
print("    WEAPONS")
print("        .binary_search_by(|(c, _, _, _, _, _)| c.cmp(&code))")
print("        .ok()")
print("        .and_then(|i| WEAPONS.get(i))")
print("        .map(|&(_, _, _, _, _, name)| name)")
print("}")
