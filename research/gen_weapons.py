"""Generate src/weapons_data.rs from blizzhackers/d2data weapons.json (D2R tables).

Usage: python3 -I research/gen_weapons.py <dir with weapons.json> > src/weapons_data.rs
Fetch the table with:
  gh api repos/blizzhackers/d2data/contents/json/weapons.json -H "Accept: application/vnd.github.raw" > weapons.json
The "speed" column is the WSM (weapon speed modifier): negative faster, positive slower;
empty cells mean 0. wtype is the weapon class (axe, bow, swor, pole, …) for mercenary
weapon filtering.
"""
import json
import sys

src = sys.argv[1]
weapons = json.load(open(f"{src}/weapons.json"))
weapons = weapons if isinstance(weapons, list) else list(weapons.values())
rows = sorted(
    (
        (r["code"], int(r.get("speed") or 0), r.get("wtype") or "")
        for r in weapons
        if r.get("code")
    ),
    key=lambda t: t[0],
)
print("//! Generated by research/gen_weapons.py from blizzhackers/d2data weapons.json (D2R). Do not edit by hand.")
print()
print("/// (item code, WSM weapon speed modifier, weapon class) per weapons.txt row; the speed is")
print("/// the classic `speed` column (negative = fast, positive = slow, 0 for empty cells).")
print(f"pub const WEAPONS: [(&str, i32, &str); {len(rows)}] = [")
for code, speed, wtype in rows:
    print(f'    ("{code}", {speed}, "{wtype}"),')
print("];")
